// WP.6H.3H: exercise the exact Result-page memory-only TSV merge function.
const fs = require('fs');
const assert = require('assert');
const view = fs.readFileSync(__dirname + '/../ecomkit-vuikhoe/admin/views/results.php', 'utf8');
const functionSource = view.match(/function currentValues\(\) \{[\s\S]*?\n    \}/);
assert(functionSource, 'Result merge function missing');
const merge = new Function('values', 'enrichment', functionSource[0] + '\nreturn currentValues();');
const first = Array(24).fill('');
first[2] = '261005S50BGX90'; first[3] = 'SHOPEE'; first[4] = 'Giao Hàng Thành Công';
first[5] = 'Existing Name'; first[6] = '09***'; first[7] = 'Existing Address';
first[14] = '312000'; first[15] = '0.298269230769230769'; first[17] = '0';
const second = first.slice(); second[2] = '261005UNMATCHED'; second[5] = 'Other Name'; second[7] = 'Other Address';
const third = first.slice(); third[3] = 'LAZADA'; third[5] = 'Lazada Name';
const base = [first, second, third].map(cells => cells.join('\t')).join('\n');
assert.strictEqual(merge(base, new Map()), base, 'No PDF should leave Ecomkit values intact');
const active = new Map([['261005S50BGX90', {name: 'Mai Example', address: 'Số 12 Đường Mẫu'}]]);
const rows = merge(base, active).split('\n').map(line => line.split('\t'));
assert.strictEqual(rows.length, 3, 'Copy row count changed');
for (const row of rows) assert.strictEqual(row.length, 24, 'Copy column count changed');
assert.strictEqual(rows[0][5], 'Mai Example');
assert.strictEqual(rows[0][7], 'Số 12 Đường Mẫu');
assert.strictEqual(rows[0][6], '09***', 'PDF changed phone');
assert.strictEqual(rows[0][14], '312000', 'PDF changed money');
assert.strictEqual(rows[0][15], '0.298269230769230769', 'PDF changed exact ratio');
assert.strictEqual(rows[0][17], '0', 'PDF changed explicit zero');
assert.strictEqual(rows[1][5], 'Other Name', 'Unmatched Shopee row changed');
assert.strictEqual(rows[2][5], 'Lazada Name', 'Non-Shopee row changed');
active.clear();
assert.strictEqual(merge(base, active), base, 'Clear did not restore Ecomkit values');
assert(!/localStorage|sessionStorage|indexedDB|document\.cookie/.test(view), 'PDF PII persisted in browser storage');
console.log('result-copy-browser-check: PASS');
